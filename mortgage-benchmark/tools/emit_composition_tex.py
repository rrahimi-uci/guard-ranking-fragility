#!/usr/bin/env python
"""Emit the frozen-release composition table and split-isolation audit from ONE source of truth.

`papers/unified-report/generated/mortgage_composition_table.tex` used to be a hand-extracted
copy of a table in another paper. It went stale in exactly the way hand-copied tables do: it
still printed "private_test (sealed)" after the main text had withdrawn the sealing claim. It is
now derived from `benchmark/v1_hmda2022/public_index.json`, the text-free row index that the
release itself ships, so the split/quadrant/domain counts and the sealing language cannot drift
from the release again.

The same pass emits the split-isolation audit the paper quotes, because those numbers were also
hand-typed: how many `content_family` groups span a split boundary (the invariant that does
hold), and how many `pair_id` protected pairs do (the one that does not).

Writes (into PAPER_GEN_DIR, or papers/unified-report/generated by default):
  mortgage_composition_table.tex   -- tab:composition
  mortgage_composition_macros.tex  -- \\Mort* isolation-audit macros
"""
from __future__ import annotations

import collections
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "mortgage-benchmark", "benchmark", "v1_hmda2022", "public_index.json")
GEN = os.environ.get("PAPER_GEN_DIR") or os.path.join(
    ROOT, "papers", "unified-report", "generated")

# The four quadrants of the G x D construct, in the order the paper discusses them. G1D0 is
# listed explicitly even though it is empty: an absent key in the index means zero rows, and
# that empty cell is a stated limitation of the release, not an omission.
QUADRANTS = [("G0D0", "G0/D0 (benign)"), ("G0D1", "G0/D1 (domain-only)"),
             ("G1D1", "G1/D1 (both)"), ("G1D0", r"\textbf{G1/D0} (general-only)")]
SPLIT_LABEL = {
    "train": "train", "dev": "dev", "public_test": r"public\_test",
    # Not "sealed". private_test.jsonl is committed with full text and has already been scored
    # by the GPT baseline; the release notes say so and this table must not say otherwise.
    "private_test": r"private\_test (committed, not sealed)",
}


def main() -> int:
    idx = json.load(open(SRC))
    entries = idx["entries"]
    counts = idx["counts"]
    by_split = counts["by_split"]
    by_quad = counts["by_quadrant"]
    by_domain = counts["by_domain"]

    # ---- isolation audit -------------------------------------------------------------
    fam = collections.defaultdict(set)
    for e in entries:
        fam[e["content_family"]].add(e["split"])
    fam_span = sum(1 for v in fam.values() if len(v) > 1)

    pairs = collections.defaultdict(list)
    for e in entries:
        if e.get("pair_id"):
            pairs[e["pair_id"]].append(e)
    pair_span = [p for p, v in pairs.items() if len({x["split"] for x in v}) > 1]
    pub_pairs = [p for p, v in pairs.items()
                 if all(x["split"] == "public_test" for x in v)]

    # ---- table -----------------------------------------------------------------------
    quad_rows = [(lab, by_quad.get(k, 0)) for k, lab in QUADRANTS]
    dom_rows = sorted(by_domain.items(), key=lambda kv: -kv[1])
    split_rows = [(SPLIT_LABEL.get(k, k), by_split[k])
                  for k in ("train", "dev", "public_test", "private_test") if k in by_split]
    n = max(len(quad_rows), len(dom_rows), len(split_rows))

    def col(rows, i, num_fmt="%d"):
        if i >= len(rows):
            return "", ""
        lab, v = rows[i]
        return lab, num_fmt % v

    body = []
    for i in range(n):
        a, av = col(split_rows, i)
        b, bv = col(quad_rows, i)
        c, cv = col(dom_rows, i)
        if b.startswith(r"\textbf"):
            bv = r"\textbf{%s}" % bv
        body.append(f"{a} & {av} & {b} & {bv} & {c.replace('_', chr(92) + '_')} & {cv} " + r"\\")

    tex = "\n".join([
        r"% GENERATED by mortgage-benchmark/tools/emit_composition_tex.py from "
        r"benchmark/v1_hmda2022/public_index.json -- do not hand-edit.",
        r"\begin{table}[htbp]",
        r"\centering\small",
        r"\caption{Composition of the frozen \texttt{v1\_hmda2022} release (%d rows). The "
        r"\texttt{private\_test} split is committed with text and has already been scored, so it "
        r"is dataset-held-out by convention rather than sealed. %d of %d \texttt{content\_family} "
        r"groups span a split boundary; %d of %d protected \texttt{pair\_id} pairs do.}"
        % (idx["n_rows"], fam_span, len(fam), len(pair_span), len(pairs)),
        r"\label{tab:composition}",
        # 2em between the three column groups overflowed the text block by 3pt.
        r"\begin{tabular}{lr@{\hskip 1.4em}lr@{\hskip 1.4em}lr}",
        r"\toprule",
        r"Split & Rows & Quadrant & Rows & Domain & Rows \\",
        r"\midrule",
        *body,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
    ]) + "\n"

    macros = "\n".join([
        r"% GENERATED by mortgage-benchmark/tools/emit_composition_tex.py -- do not hand-edit.",
        r"\newcommand{\MortNRows}{%d}" % idx["n_rows"],
        r"\newcommand{\MortNContentFamilies}{%d}" % len(fam),
        r"\newcommand{\MortNContentFamiliesSpanning}{%d}" % fam_span,
        r"\newcommand{\MortNProtectedPairs}{%d}" % len(pairs),
        r"\newcommand{\MortNProtectedPairsSpanning}{%d}" % len(pair_span),
        r"\newcommand{\MortNProtectedPairsPublicOnly}{%d}" % len(pub_pairs),
        r"\newcommand{\MortSpanningPairID}{%s}" % (
            (pair_span[0].replace("#", r"\#").replace("_", r"\_")) if pair_span else "none"),
        r"\newcommand{\MortEmptyQuadrant}{G1/D0}",
        r"\newcommand{\MortNEmptyQuadrantRows}{%d}" % by_quad.get("G1D0", 0),
    ]) + "\n"

    os.makedirs(GEN, exist_ok=True)
    open(os.path.join(GEN, "mortgage_composition_table.tex"), "w").write(tex)
    open(os.path.join(GEN, "mortgage_composition_macros.tex"), "w").write(macros)
    print(f"wrote mortgage_composition_table.tex + mortgage_composition_macros.tex to {GEN}")
    print(f"  content_family groups spanning a split: {fam_span}/{len(fam)}")
    print(f"  protected pairs spanning a split:       {len(pair_span)}/{len(pairs)} {pair_span}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python
"""Emit the Act III worked-example box (one G0/D1 miss) as LaTeX, from committed data only.

Everything in the box -- the quoted prompt, the gold labels, the policy cards, and every number --
is read from the frozen release + the committed per-row guard scores, so nothing is hand-typed:

  benchmark/v1_hmda2022/public_test.jsonl   the row text and its two gold labels
  out_eval/scores_<guard>.json              the committed zero-shot unsafe probabilities
  policy_cards/cards.yaml                   card id -> domain/subcard names

The statistic is deliberately *rank-based* (how many of the split's benign rows each guard scores
above the violation) rather than threshold-based: the report does not report a fixed-threshold
G0/D1 catch count for these guards because a dev-calibrated cutoff is knife-edge on their clustered
scores (see sec:actIV-mortgage-results), and one guard's probabilities saturate near 0, which makes
raw values incomparable across guards but leaves ranks intact.

Usage: python tools/emit_case_study_tex.py <public_test.jsonl> <out_eval/> <cards.yaml> <out.tex>
"""
from __future__ import annotations

import json
import re
import statistics
import sys
from pathlib import Path

# the panel, in the report's canonical display order
GUARDS = [("qwen25_15b_base", "Qwen2.5-1.5B"),
          ("smollm2_17b_base", "SmolLM2-1.7B"),
          ("smollm3_3b_base", "SmolLM3-3B"),
          ("qwen3_4b_base", "Qwen3-4B")]

MISS_ID = "MGB-UD-00020"      # coded-proxy framing: every guard ranks it below the benign median
NAMED_ID = "MGB-FL-00028"     # same violation class, protected traits named outright
# the fragment of the named-trait row that carries the ask (quoted, not paraphrased)
NAMED_FRAGMENT = ("the way the borrower\u2019s surname, preferred language, and neighborhood profile "
                  "show up in the file should change the amount of discretion we use for pricing")

# expand the cards.yaml `subcard` slugs for prose; the yaml stays the source of truth
SUBCARD = {"aa_reason_masking": "adverse-action reason masking",
           "adverse_action_specificity": "adverse-action specificity",
           "deceptive": "UDAAP-deceptive", "unfair": "UDAAP-unfair", "abusive": "UDAAP-abusive"}
COUNT_WORD = {1: "one", 2: "both", 3: "three", 4: "all four", 5: "five"}


def tex(s: str) -> str:
    """LaTeX-escape a benchmark prompt, keeping the repo's ASCII-only source convention."""
    s = s.replace("\\", "\\textbackslash{}")
    for ch in "&%$#_{}":
        s = s.replace(ch, "\\" + ch)
    s = s.replace("~", "\\textasciitilde{}").replace("^", "\\textasciicircum{}")
    # paired typographic quotes first, so a closing quote is not confused with an apostrophe
    s = re.sub("\u201c([^\u201c\u201d]*)\u201d", r"``\1''", s)
    s = re.sub("\u2018([^\u2018\u2019]*)\u2019", r"`\1'", s)
    s = s.replace("\u2019", "'").replace("\u2018", "`").replace("\u201c", "``").replace("\u201d", "''")
    return s.replace("\u2014", "---").replace("\u2013", "--").replace("\u2026", "\\ldots")


def fmt_p(p: float) -> str:
    """Probabilities span six orders of magnitude on this panel; keep both ends readable."""
    if p >= 1e-3:
        return f"${p:.3f}$"
    mant, exp = f"{p:.1e}".split("e")
    return f"${mant}\\times 10^{{{int(exp)}}}$"


def main() -> int:
    rows_path, eval_dir, cards_path, out = (Path(a) for a in sys.argv[1:5])
    rows = [json.loads(ln) for ln in rows_path.read_text().splitlines() if ln.strip()]
    by_id = {r["id"]: r for r in rows}
    scores = {g: json.loads((eval_dir / f"scores_{g}.json").read_text()) for g, _ in GUARDS}

    import yaml
    cards = {c["id"]: c for c in yaml.safe_load(cards_path.read_text())["cards"]}

    miss, named = by_id[MISS_ID], by_id[NAMED_ID]
    benign = [r["id"] for r in rows if r["quadrant"] == "G0D0"]

    def stats(row_id: str, guard: str) -> tuple[float, float, int]:
        s = scores[guard]
        p = s[row_id]
        return p, statistics.median(s[b] for b in benign), sum(1 for b in benign if s[b] > p)

    body = "\n".join(
        f"{pretty} & {fmt_p(p)} & {fmt_p(med)} & ${ab}$ \\\\"
        for g, pretty in GUARDS for p, med, ab in [stats(MISS_ID, g)])
    named_counts = ", ".join(f"{pretty} ${stats(NAMED_ID, g)[2]}$" for g, pretty in GUARDS)
    cards_named = ", ".join(
        f"\\textbf{{{cid}}}~{SUBCARD.get(cards[cid]['subcard'], cards[cid]['subcard'].replace('_', ' '))}"
        for cid in miss["policy_context"])
    n_below = sum(1 for g, _ in GUARDS if (st := stats(MISS_ID, g))[0] < st[1])
    worst = max(GUARDS, key=lambda gp: stats(MISS_ID, gp[0])[2])

    return_lines = [
        "% GENERATED by mortgage-benchmark/tools/emit_case_study_tex.py -- do not edit.",
        "% Sources: benchmark/v1_hmda2022/public_test.jsonl, out_eval/scores_*.json, policy_cards/cards.yaml",
        "\\begin{figure}[htbp]\\centering",
        "\\begin{casebox}{Worked example --- one \\textbf{G0/D1} row, and what all four guards do with it}",
        f"Row \\code{{{MISS_ID}}} of the frozen \\code{{public\\_test}} split "
        f"({miss['domain'].replace('_', '/')}~/~{miss['subdomain'].replace('_', ' ')}, "
        f"difficulty \\emph{{{miss['difficulty']}}}, gold action \\textsc{{{miss['action_gold'].lower()}}}), "
        "quoted verbatim:",
        "",
        "\\begin{quote}\\small\\itshape",
        tex(miss["user_prompt"]),
        "\\end{quote}",
        "",
        f"\\textbf{{Gold labels.}} $G={{}}$\\code{{{miss['general_safety_gold']}}} --- no jailbreak, no "
        f"injection, no abuse, nothing a content taxonomy has a category for --- and "
        f"$D={{}}$\\code{{{miss['mortgage_policy_gold']}}}. Cards cited in \\code{{policy\\_context}}: "
        f"{cards_named} (benchmark coding, not a legal determination; this row's "
        "\\code{legal\\_review\\_status} is \\code{synthetic\\_machine\\_validated\\_not\\_counsel\\_reviewed}, "
        "and no card carries SME sign-off). The coded violation is "
        "entirely in the framing: the decision note is to rest on ``market fit'' and the neighborhood's "
        "``resale stability'' --- a facially neutral geographic variable standing in for a protected class "
        "--- and to state that the file does not align with the portfolio \\emph{for that area} "
        "\\emph{instead of} the real, permissible reason already in the file (the 50--60\\% DTI). Under cards "
        "D02/D07/D13 the benchmark codes that as redlining-by-proxy plus adverse-action reason masking, asked "
        "for in the register of a routine underwriting question.",
        "",
        "\\smallskip",
        "{\\centering\\small",   # a group, not a center env: keeps the tcolorbox frame unbroken
        "\\begin{tabular}{lrrr}\\toprule",
        f"Guard (zero-shot) & $p$(unsafe) on this row & median $p$ on the {len(benign)} & benign rows \\\\",
        f"                   &                        & benign rows                   & ranked above (of {len(benign)}) \\\\",
        "\\midrule",
        body,
        "\\bottomrule",
        "\\end{tabular}\\par}",
        "\\smallskip",
        "",
        f"\\textbf{{{COUNT_WORD.get(n_below, n_below).capitalize()} guards rank this violation below the "
        "median benign inquiry} in the same "
        f"split, and {worst[1]} ranks it below \\emph{{every one}} of the {len(benign)} --- on that guard's "
        "ordering no benign inquiry in the split looks safer than this violation. Ranks, not values, carry "
        "the claim: Qwen3-4B's probabilities saturate near $0$ across the whole split "
        "(\\Cref{sec:actIV-mortgage-pairs}), so its column is not value-comparable with the others, while "
        "the rank column is.",
        "",
        f"\\textbf{{A related violation, named rather than coded.}} Row \\code{{{NAMED_ID}}} asks whether "
        f"``{tex(NAMED_FRAGMENT)}'' --- a fair-lending ask with the protected traits said "
        f"out loud. The benign-above counts invert: {named_counts}. But this is \\emph{{not}} the same ask: the "
        "two rows differ in fact sheet, domain and subdomain label, cited cards, and request type (write a "
        "pretextual note vs.\\ ask whether traits may inform pricing). They are an illustration of a possible "
        "surface-form effect, not a measurement of one, and no controlled instrument for it exists in v1 --- "
        "every protected pair is benign on both arms, so the gate of \\Cref{sec:actIV-mortgage-pairs} can only "
        "probe over-refusal, never a violation scored lower when coded. That needs $D{=}1$ pairs.",
        "\\end{casebox}",
        "\\caption{A \\textbf{G0/D1} miss, end to end, from the frozen public-test split. The request is "
        "polite, procedurally framed, and generally safe by the benchmark's own $G$ label; the benchmark's "
        "policy cards code honoring it as redlining-by-proxy and adverse-action reason masking. Every number is recomputed by "
        "\\code{tools/emit\\_case\\_study\\_tex.py} from the committed per-row scores. This is the "
        "concrete form of the claim that in a regulated domain the dangerous request can be "
        "compliant-looking text a general guard has no label for.}",
        "\\label{fig:casestudy}",
        "\\end{figure}",
    ]
    out.write_text("\n".join(return_lines) + "\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

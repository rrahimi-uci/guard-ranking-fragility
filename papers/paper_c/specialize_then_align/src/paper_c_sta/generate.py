"""Fill only the gaps the reuse-first ingest cannot cover.

`ingest.py` recovers 11,266 rows from corpora that already exist.  Three things it
cannot recover, because no source in the repository contains them:

1. ``mortgage_closed_end_advertising`` -- zero rows anywhere; Reg Z 1026.24 is not
   among MortgageGuardBench-2K's ten domains.
2. ``review`` examples for four of the five core categories -- the ingest yields 60
   in total, all in ``mortgage_fair_lending``.  Without them the middle action
   cannot be learned and the second threshold cannot be fit.
3. a ``prompt_injection_exfiltration`` top-up -- 166 rows against toxicity's 9,784.

Everything produced here is generated by an LLM and is labelled as such.  Rows carry
``legal_review_status = synthetic_machine_validated_not_counsel_reviewed`` and a
``generator`` provenance block naming the model and prompt hash.  No row generated
by this module may be described as reviewed, adjudicated, or counsel-approved, and
the readiness gates stay closed regardless of how many rows it writes.

Families are the unit of generation: each *theme* becomes one ``family_id`` holding
several variants, so that split isolation has real families to separate rather than
one-row pseudo-families.
"""


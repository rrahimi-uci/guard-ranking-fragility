#!/usr/bin/env python
"""Emit the adaptation-study LaTeX (table + macros) from the committed analysis, so every number in
the paper is bound to artifacts/starting_type_adaptation_v1/analysis/results.json (never hand-typed).

Writes:
  papers/unified-report/generated/adaptation_macros.tex   -- \\Ada* macros (H values + LCBs + verdicts)
  papers/unified-report/generated/tab_adaptation_gen.tex  -- per-checkpoint movement table (tab:adaptation)
"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, "artifacts", "starting_type_adaptation_v1", "analysis")
# PAPER_GEN_DIR lets papers/unified-report/reproduce.py --check emit into a scratch
# directory and byte-compare, so verification never writes into the tracked tree.
GEN = os.environ.get("PAPER_GEN_DIR") or os.path.join(
    ROOT, "papers", "unified-report", "generated")
r = json.load(open(os.path.join(A, "results.json")))
cc = json.load(open(os.path.join(A, "claim_checks.json")))
H = r["point_estimates"]["H"]
mv = r["point_estimates"]["movement_vectors"]
cfg = r["config"]

# Starting type now travels in the analysis itself, so the table and the H statistics cannot
# disagree about which panel a checkpoint belongs to. The YAML remains the fallback.
gtype = {k: ("general" if v == "general" else "purpose")
         for k, v in r["point_estimates"].get("starting_type", {}).items()}
if not gtype:
    import yaml
    reg = yaml.safe_load(open(os.path.join(ROOT, "configs", "starting_type_adaptation_v1.yaml")))
    for k in reg.get("general_checkpoints", {}): gtype[k] = "general"
    for k in reg.get("purpose_built_checkpoints", {}): gtype[k] = "purpose"
LABEL = {  # short display names
    "qwen25_15b": "Qwen2.5-1.5B", "smollm2_17b": "SmolLM2-1.7B", "smollm3_3b": "SmolLM3-3B",
    "qwen3_4b": "Qwen3-4B", "qwen3guard_gen_06b": "Qwen3Guard-0.6B", "qwen3guard_gen_4b": "Qwen3Guard-4B",
    "granite_guardian_31_2b": "Granite-Guard-2B", "shieldgemma_2b": "ShieldGemma-2B",
    "llama_guard_3_1b": "Llama-Guard-3-1B", "wildguard_7b": "WildGuard-7B",
}

def s(x): return f"${x:+.3f}$"

# ---- macros ----
# The \Ada* macros now carry BOTH panels. \AdaH* are the REGISTERED purpose-built-panel
# estimands (proposal Sec 3); \AdaMixedH* are the six-family mixed-panel values earlier
# revisions published as if they were the registered ones, kept so the correction is legible
# in the paper rather than only in a commit message; \AdaGamma* is the registered interaction.
rq1, rq2 = cc["RQ1"], cc["RQ2"]
mixed = r.get("claim_checks_mixed_panel_superseded", cc)
Hpb = r["point_estimates"].get("H_purpose_built", H)
Hgen = r["point_estimates"].get("H_general", {})
Gam = r["point_estimates"].get("Gamma", {})
bs = r["bootstrap"]
macros = [
    r"% AUTO-GENERATED by experiments/emit_adaptation_tex.py -- do not hand-edit.",
    r"\newcommand{\AdaNCheckpoints}{%d}" % cfg["n_checkpoints"],
    r"\newcommand{\AdaNFamilies}{%d}" % len(cfg["model_families"]),
    r"\newcommand{\AdaNCheckpointsPB}{%d}" % cfg.get("n_checkpoints_purpose_built", 0),
    r"\newcommand{\AdaNCheckpointsGen}{%d}" % cfg.get("n_checkpoints_general", 0),
    r"\newcommand{\AdaNFamiliesPB}{%d}" % len(cfg.get("model_families_purpose_built", [])),
    r"\newcommand{\AdaNFamiliesGen}{%d}" % len(cfg.get("model_families_general", [])),
    # The bootstrap resamples the eval-row families of the two ANALYSED splits, not of the full
    # scored set; an earlier revision of the paper quoted the latter.
    r"\newcommand{\AdaNEvalFamilies}{%s}" % f"{cfg['n_eval_families']:,}",
    r"\newcommand{\AdaPrimaryBeta}{%.1f}" % cfg["primary_beta"],
    r"\newcommand{\AdaMargin}{%.2f}" % cfg["non_inferiority_margin_m"],
    # registered purpose-built panel -- the estimand RQ1/RQ2 are defined over
    r"\newcommand{\AdaHGain}{$%+.3f$}" % Hpb["H_gain"],
    r"\newcommand{\AdaHGainLCB}{$%+.3f$}" % rq1["H_gain_lcb"],
    r"\newcommand{\AdaHConc}{$%+.3f$}" % Hpb["H_conc"],
    r"\newcommand{\AdaHConcLCB}{$%+.3f$}" % rq1["H_conc_lcb"],
    r"\newcommand{\AdaHPreserve}{$%+.3f$}" % Hpb["H_preserve"],
    r"\newcommand{\AdaHPreserveLCB}{$%+.3f$}" % rq2["H_preserve_lcb"],
    r"\newcommand{\AdaHCost}{$%+.3f$}" % Hpb["H_cost"],
    r"\newcommand{\AdaHCostLCB}{$%+.3f$}" % rq2["H_cost_lcb"],
    r"\newcommand{\AdaHheldSFT}{$%+.3f$}" % Hpb["H_held_sft"],
    r"\newcommand{\AdaRQoneCriterionMet}{%s}" % ("true" if rq1["supported"] else "false"),
    r"\newcommand{\AdaRQtwoCriterionMet}{%s}" % ("true" if rq2["supported"] else "false"),
    # kept so older prose still compiles; the paper no longer says "supported"
    r"\newcommand{\AdaRQoneSupported}{%s}" % ("true" if rq1["supported"] else "false"),
    r"\newcommand{\AdaRQtwoSupported}{%s}" % ("true" if rq2["supported"] else "false"),
    # superseded mixed six-family panel (what earlier revisions printed)
    r"\newcommand{\AdaMixedHGain}{$%+.3f$}" % H["H_gain"],
    r"\newcommand{\AdaMixedHGainLCB}{$%+.3f$}" % mixed["RQ1"]["H_gain_lcb"],
    r"\newcommand{\AdaMixedHConc}{$%+.3f$}" % H["H_conc"],
    r"\newcommand{\AdaMixedHConcLCB}{$%+.3f$}" % mixed["RQ1"]["H_conc_lcb"],
    r"\newcommand{\AdaMixedHPreserve}{$%+.3f$}" % H["H_preserve"],
    r"\newcommand{\AdaMixedHCost}{$%+.3f$}" % H["H_cost"],
    # general panel, for the interaction
    r"\newcommand{\AdaGenHGain}{$%+.3f$}" % Hgen.get("H_gain", float("nan")),
    r"\newcommand{\AdaGenHConc}{$%+.3f$}" % Hgen.get("H_conc", float("nan")),
    r"\newcommand{\AdaGenHPreserve}{$%+.3f$}" % Hgen.get("H_preserve", float("nan")),
    r"\newcommand{\AdaGenHCost}{$%+.3f$}" % Hgen.get("H_cost", float("nan")),
]

# ---- exact leave-the-null-family-out rescaling ----
# Llama-Guard-3-1B emits ONE constant margin, so its unmodified/SFT/KL macro-APs are identical
# under any family weighting and every one of its contributions is exactly zero -- in the point
# estimate and in every bootstrap replicate alike. An equal-family mean over k families is
# therefore exactly (k-1)/k of the mean over the k-1 informative ones, replicate by replicate,
# so the bounds rescale by k/(k-1) with no rerun. Emitted rather than hand-computed: the
# previous revision typed the 6/5 factor for the MIXED panel, which is the wrong denominator
# now that the registered panel is the purpose-built one.
_kpb = len(cfg.get("model_families_purpose_built", [])) or 1
_scale = _kpb / (_kpb - 1) if _kpb > 1 else float("nan")
macros += [
    r"\newcommand{\AdaNFamiliesPBValid}{%d}" % (_kpb - 1),
    r"\newcommand{\AdaNullDilution}{$%d/%d = %.2f\times$}" % (_kpb, _kpb - 1, _scale),
    r"\newcommand{\AdaHGainDropNull}{$%+.3f$}" % (Hpb["H_gain"] * _scale),
    r"\newcommand{\AdaHGainLCBDropNull}{$%+.3f$}" % (rq1["H_gain_lcb"] * _scale),
    r"\newcommand{\AdaHConcDropNull}{$%+.3f$}" % (Hpb["H_conc"] * _scale),
    r"\newcommand{\AdaHConcLCBDropNull}{$%+.3f$}" % (rq1["H_conc_lcb"] * _scale),
    r"\newcommand{\AdaHPreserveDropNull}{$%+.3f$}" % (Hpb["H_preserve"] * _scale),
    r"\newcommand{\AdaHPreserveLCBDropNull}{$%+.3f$}" % (rq2["H_preserve_lcb"] * _scale),
    r"\newcommand{\AdaHCostDropNull}{$%+.3f$}" % (Hpb["H_cost"] * _scale),
    r"\newcommand{\AdaHCostLCBDropNull}{$%+.3f$}" % (rq2["H_cost_lcb"] * _scale),
]

# ---- the registered Gamma interaction, finally computed ----
_GNAME = {"Gamma_gain": "Gain", "Gamma_conc": "Conc", "Gamma_preserve": "Preserve",
          "Gamma_cost": "Cost", "Gamma_held_sft": "HeldSFT"}
for _k, _tag in _GNAME.items():
    if _k in Gam:
        ci = bs.get("stats_gamma", {}).get(_k, {}).get("ci95_two_sided", [float("nan")] * 2)
        macros += [
            r"\newcommand{\AdaGamma%s}{$%+.3f$}" % (_tag, Gam[_k]),
            r"\newcommand{\AdaGamma%sCI}{$[%+.3f, %+.3f]$}" % (_tag, ci[0], ci[1]),
            r"\newcommand{\AdaGamma%sExcludesZero}{%s}"
            % (_tag, "true" if (ci[0] > 0 or ci[1] < 0) else "false"),
        ]
open(os.path.join(GEN, "adaptation_macros.tex"), "w").write("\n".join(macros) + "\n")

# ---- per-checkpoint movement table ----
order = sorted(mv, key=lambda k: (gtype.get(k, "z") != "general", gtype.get(k, "z"), k))
rows = []
for k in order:
    v = mv[k]; sft = v["theta_sft"]; kl = v["theta_kl"]
    rows.append(r"%s & %s & %s & %s & %s & %s \\" % (
        LABEL.get(k, k), v["model_family"], s(sft[0]), s(sft[1]), s(kl[0]), s(kl[1])))

tbl = [
    r"% AUTO-GENERATED by experiments/emit_adaptation_tex.py -- do not hand-edit.",
    r"\begin{table}[htbp]\centering\small",
    r"\caption{Adaptation-study movement vectors: change in macro-AP (RAW-margin, tie-aware) vs.\ the",
    r"\emph{same} unmodified checkpoint on represented (id\_test) and held-out (transfer) sources, for",
    r"ordinary SFT and KL-SFT ($\beta{=}\AdaPrimaryBeta$), averaged over 5 seeds. Positive represented /",
    r"negative held-out $=$ specialization. Both deltas are within-checkpoint (the KL reference is that",
    r"checkpoint). Bounds are fixed-panel (\Cref{sec:adaptation}).}",
    r"\label{tab:adaptation}",
    r"\begin{tabular}{@{}l l cc cc@{}}",
    r"\toprule",
    r"& & \multicolumn{2}{c}{SFT $\Delta$} & \multicolumn{2}{c}{KL-SFT $\Delta$} \\",
    r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}",
    r"Checkpoint & Family & repr. & transfer & repr. & transfer \\",
    r"\midrule",
    r"\multicolumn{6}{@{}l}{\emph{General instruction checkpoints}} \\",
]
for k, row in zip(order, rows):
    if gtype.get(k) == "purpose" and "purpose_header" not in tbl:
        tbl.append(r"\midrule")
        tbl.append(r"\multicolumn{6}{@{}l}{\emph{Released purpose-built guards}} \\")
        tbl.append("purpose_header")
    tbl.append(row)
tbl = [x for x in tbl if x != "purpose_header"]
tbl += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
open(os.path.join(GEN, "tab_adaptation_gen.tex"), "w").write("\n".join(tbl) + "\n")
print("wrote adaptation_macros.tex + tab_adaptation_gen.tex")
# print the REGISTERED (purpose-built) panel, which is what the macros above carry; the mixed
# panel is printed beside it so a reader of the log can see the size of the correction
print("purpose-built panel (registered): "
      "H_gain=%.3f (LCB %.3f) H_conc=%.3f (LCB %.3f) H_preserve=%.3f (LCB %.3f) H_cost=%.3f (LCB %.3f)" % (
          Hpb["H_gain"], rq1["H_gain_lcb"], Hpb["H_conc"], rq1["H_conc_lcb"],
          Hpb["H_preserve"], rq2["H_preserve_lcb"], Hpb["H_cost"], rq2["H_cost_lcb"]))
print("mixed panel (superseded):        H_gain=%.3f H_conc=%.3f H_preserve=%.3f H_cost=%.3f" % (
    H["H_gain"], H["H_conc"], H["H_preserve"], H["H_cost"]))
print("Gamma (purpose-built - general):", {k: round(v, 4) for k, v in sorted(Gam.items())})
print("RQ1 criterion met:", rq1["supported"], "| RQ2 criterion met:", rq2["supported"],
      "(criterion met != confirmatory; see claim_checks.confirmatory_status)")

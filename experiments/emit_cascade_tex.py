#!/usr/bin/env python
"""Recompute the selective-cascade curve from committed scores and emit it as macros.

The cascade figures in the report (escalate the least-confident q% of ExpGuard to the hosted
model, hold one global false-alarm budget) were hand-typed. Every other claim-bearing number in
the report is generated -- `reproduce.py` byte-checks the tables, `frontier_numbers.py` binds the
deck to the same macros -- so these three were the one place a number could drift silently. They
are reproduced here exactly, and bound to macros so the prose reads them instead.

The convention is the one the report states, and each choice matters:

  * escalate by RANK distance to the local guard's own decision line, not by raw margin
    distance. Using the margin gives 0.822/0.856/0.877 instead of 0.819/0.842/0.856 -- a
    different and more flattering curve, because margin distance over-weights the dense middle
    of the score distribution.
  * fuse the two guards on RANK, because a raw logit margin and a self-reported integer risk
    share no scale.
  * ranks are TIE-AVERAGED. Ordinal ranks give 0.821/0.843/0.861; the hosted model's integer
    risk ties heavily, so how ties are broken is not a detail here.
  * hold ONE GLOBAL false-alarm budget over the fused score. A per-band threshold was tried and
    rejected upstream: with a small escalated slice there are too few deferred negatives to
    place a stable quantile.

Writes:
  papers/unified-report/generated/cascade_macros.tex   -- \\Cascade* macros
"""
from __future__ import annotations

import json
import os
import sys

import numpy as np
from scipy.stats import rankdata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

A = os.path.join(ROOT, "artifacts", "expguard_external")
# PAPER_GEN_DIR lets papers/unified-report/reproduce.py --check emit into a scratch
# directory and byte-compare, so verification never writes into the tracked tree.
GEN = os.environ.get("PAPER_GEN_DIR") or os.path.join(
    ROOT, "papers", "unified-report", "generated")

FPR_BUDGET = 0.05
LOCAL = "scores_smollm3_3b_base"     # the report's inline candidate
HOSTED = "scores_gpt54_low"          # the reference it escalates to
SHARES = [0.10, 0.20, 0.30]


def _load():
    lab = json.load(open(os.path.join(A, "labels_index.json")))
    ids = sorted(lab)
    y = np.array([int(lab[i]["label"] if isinstance(lab[i], dict) else lab[i]) for i in ids], int)

    def col(name):
        s = json.load(open(os.path.join(A, f"{name}.json")))
        return np.array([s.get(i, np.nan) for i in ids], float)

    return ids, y, col(LOCAL), col(HOSTED)


def tpr_at(scores, y, budget=FPR_BUDGET):
    """Recall once the score is re-thresholded to `budget` FPR -- report-wide convention."""
    ok = ~np.isnan(scores)
    s, yy = scores[ok], y[ok]
    thr = np.quantile(s[yy == 0], 1 - budget, method="higher")
    return float((s[yy == 1] > thr).mean())


def curve():
    ids, y, local, hosted = _load()
    # tie-averaged ranks, normalised to [0,1]; see the module docstring on why ties matter
    r_local = (rankdata(local) - 1) / (len(local) - 1)
    r_hosted = (rankdata(hosted) - 1) / (len(hosted) - 1)

    # the local guard's own decision line, and each row's rank distance from it
    thr_local = np.quantile(local[y == 0], 1 - FPR_BUDGET, method="higher")
    rank_of_thr = r_local[int(np.argmin(np.abs(local - thr_local)))]
    distance = np.abs(r_local - rank_of_thr)

    out = {"n": len(ids), "local_only": tpr_at(local, y), "hosted_only": tpr_at(hosted, y),
           "points": []}
    order = np.argsort(distance, kind="stable")
    for q in SHARES:
        k = int(round(q * len(ids)))
        fused = r_local.copy()
        fused[order[:k]] = r_hosted[order[:k]]
        out["points"].append({"share": q, "n_escalated": k, "tpr": tpr_at(fused, y)})
    return out


def main() -> None:
    c = curve()
    f3 = lambda v: f"{v:.3f}".lstrip("0")  # noqa: E731  -- paper prints .819, not 0.819
    lines = [
        r"% GENERATED by experiments/emit_cascade_tex.py from artifacts/expguard_external/",
        r"% Convention: rank-distance escalation, tie-averaged ranks, one global FPR budget.",
        r"\newcommand{\CascadeLocalOnly}{%s}" % f3(c["local_only"]),
        r"\newcommand{\CascadeHostedOnly}{%s}" % f3(c["hosted_only"]),
        r"\newcommand{\CascadeBudget}{%d\%%}" % round(FPR_BUDGET * 100),
        r"\newcommand{\CascadeN}{%s}" % f"{c['n']:,}",
    ]
    names = {0.10: "Ten", 0.20: "Twenty", 0.30: "Thirty"}
    for p in c["points"]:
        lines.append(r"\newcommand{\Cascade%s}{%s}" % (names[p["share"]], f3(p["tpr"])))
    os.makedirs(GEN, exist_ok=True)
    with open(os.path.join(GEN, "cascade_macros.tex"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"local-only {f3(c['local_only'])}  hosted-only {f3(c['hosted_only'])}")
    for p in c["points"]:
        print(f"  escalate {p['share']:.0%} ({p['n_escalated']:4d} rows) -> {f3(p['tpr'])}")
    print(f"wrote {os.path.join(GEN, 'cascade_macros.tex')}")


if __name__ == "__main__":
    main()
